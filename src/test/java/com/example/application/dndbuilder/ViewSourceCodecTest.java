package com.example.application.dndbuilder;

import com.vaadin.flow.component.button.Button;
import com.vaadin.flow.component.formlayout.FormLayout;
import com.vaadin.flow.component.grid.Grid;
import com.vaadin.flow.component.orderedlayout.HorizontalLayout;
import com.vaadin.flow.component.orderedlayout.VerticalLayout;
import com.vaadin.flow.component.textfield.TextField;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class ViewSourceCodecTest {

    private static final String JAVADOC = """
            /**
             * Generated by the DnD builder. Do not edit: every save from the builder overwrites this method.
             * Once the view is no longer designed with the builder, this method may be edited and renamed freely.
             */
            """;

    private final ViewSourceCodec codec = new ViewSourceCodec();

    @Test
    void renderMethod_nestedTree_addsEachChildToItsParent() {
        DesignNode root = new DesignNode(VerticalLayout.class, null,
                new DesignNode(TextField.class, "Name"),
                new DesignNode(HorizontalLayout.class, null,
                        new DesignNode(Button.class, "Save"),
                        new DesignNode(Button.class, "Cancel")));

        assertEquals(JAVADOC + """
                private void _initLayout() {
                    TextField textField1 = new TextField("Name");
                    HorizontalLayout horizontalLayout1 = new HorizontalLayout();
                    Button button1 = new Button("Save");
                    Button button2 = new Button("Cancel");
                    horizontalLayout1.add(button1, button2);
                    add(textField1, horizontalLayout1);
                }""", codec.renderMethod(root));
    }

    @Test
    void renderMethod_textWithQuotes_isEscaped() {
        DesignNode root = new DesignNode(VerticalLayout.class, null, new DesignNode(Button.class, "Say \"hi\""));

        assertEquals(JAVADOC + """
                private void _initLayout() {
                    Button button1 = new Button("Say \\"hi\\"");
                    add(button1);
                }""", codec.renderMethod(root));
    }

    @Test
    void renderMethod_textWithBackslashAndNewline_isEscaped() {
        DesignNode root = new DesignNode(VerticalLayout.class, null, new DesignNode(Button.class, "C:\\temp\nnext"));

        assertEquals(JAVADOC + """
                private void _initLayout() {
                    Button button1 = new Button("C:\\\\temp\\nnext");
                    add(button1);
                }""", codec.renderMethod(root));
    }

    @Test
    void renderMethod_sameTypeUnderDifferentParents_countsPerTypeAcrossTheTree() {
        DesignNode root = new DesignNode(VerticalLayout.class, null,
                new DesignNode(HorizontalLayout.class, null,
                        new DesignNode(HorizontalLayout.class, null, new DesignNode(Button.class, "Deep"))),
                new DesignNode(Button.class, "Top"));

        assertEquals(JAVADOC + """
                private void _initLayout() {
                    HorizontalLayout horizontalLayout1 = new HorizontalLayout();
                    HorizontalLayout horizontalLayout2 = new HorizontalLayout();
                    Button button1 = new Button("Deep");
                    horizontalLayout2.add(button1);
                    horizontalLayout1.add(horizontalLayout2);
                    Button button2 = new Button("Top");
                    add(horizontalLayout1, button2);
                }""", codec.renderMethod(root));
    }

    @Test
    void renderMethod_emptyTree_rendersEmptyMethod() {
        assertEquals(JAVADOC + """
                private void _initLayout() {
                }""", codec.renderMethod(new DesignNode(VerticalLayout.class, null)));
    }

    @Test
    void read_renderedMethod_givesTheSameTree() {
        DesignNode root = new DesignNode(VerticalLayout.class, null,
                new DesignNode(TextField.class, "Name"),
                new DesignNode(HorizontalLayout.class, null,
                        new DesignNode(Button.class, "Say \"hi\""),
                        new DesignNode(HorizontalLayout.class, null)),
                new DesignNode(Button.class, null));

        assertEquals(root, codec.read(viewSource("VerticalLayout", codec.renderMethod(root))));
    }

    @Test
    void read_withoutMethod_givesRootWithoutChildren() {
        assertEquals(new DesignNode(HorizontalLayout.class, null), codec.read(viewSource("HorizontalLayout", "")));
    }

    @Test
    void read_onDemandImport_resolvesTheType() {
        String source = """
                import com.vaadin.flow.component.orderedlayout.*;

                public class SampleView extends VerticalLayout {
                    private void _initLayout() {
                        HorizontalLayout row = new HorizontalLayout();
                        add(row);
                    }
                }
                """;

        assertEquals(new DesignNode(VerticalLayout.class, null, new DesignNode(HorizontalLayout.class, null)),
                codec.read(source));
    }

    @Test
    void read_viewUsingJava21Syntax_isParsed() {
        String source = viewSource("VerticalLayout", """
                private record Row(String name) {
                }

                private String describe(Object value) {
                    return switch (value) {
                        case String text -> text;
                        default -> \"""
                                other\""";
                    };
                }
                """);

        assertEquals(new DesignNode(VerticalLayout.class, null), codec.read(source));
    }

    @Test
    void read_unsupportedStatement_failsNamingIt() {
        String source = viewSource("VerticalLayout", """
                private void _initLayout() {
                    Button button1 = new Button("Save");
                    button1.setEnabled(false);
                    add(button1);
                }
                """);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> codec.read(source));
        assertTrue(exception.getMessage().contains("button1.setEnabled(false);"), exception.getMessage());
    }

    @Test
    void read_componentNeverAdded_fails() {
        String source = viewSource("VerticalLayout", """
                private void _initLayout() {
                    Button button1 = new Button("Lost");
                }
                """);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> codec.read(source));
        assertTrue(exception.getMessage().contains("button1"), exception.getMessage());
    }

    @Test
    void read_componentAddedTwice_fails() {
        String source = viewSource("VerticalLayout", """
                private void _initLayout() {
                    Button button1 = new Button("Twice");
                    add(button1);
                    add(button1);
                }
                """);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> codec.read(source));
        assertTrue(exception.getMessage().contains("add(button1);"), exception.getMessage());
    }

    @Test
    void read_viewWithoutSuperType_fails() {
        assertThrows(IllegalArgumentException.class, () -> codec.read("public class SampleView {\n}\n"));
    }

    @Test
    void read_helperClassBeforeRouteView_readsTheRouteView() {
        String source = viewSource("HorizontalLayout", "")
                .replace("public class SampleView", "class Helper extends VerticalLayout {\n}\n\n@Route(\"sample\")\npublic class SampleView");

        assertEquals(new DesignNode(HorizontalLayout.class, null), codec.read(source));
    }

    @Test
    void findRouteViewType_routeView_givesItsSuperType() {
        String source = viewSource("HorizontalLayout", "").replace("public class", "@Route(\"sample\")\npublic class");

        assertEquals(Optional.of(HorizontalLayout.class), codec.findRouteViewType(source));
    }

    @Test
    void findRouteViewType_withoutRoute_givesEmpty() {
        assertEquals(Optional.empty(), codec.findRouteViewType(viewSource("VerticalLayout", "")));
    }

    @Test
    void write_existingMethod_replacesOnlyTheMethod() {
        String source = """
                package com.example.views;

                import com.vaadin.flow.component.button.Button;
                import com.vaadin.flow.component.orderedlayout.VerticalLayout;
                import com.vaadin.flow.router.Route;

                // hand-written,   oddly   formatted code must survive
                @Route("sample")
                public class SampleView extends VerticalLayout {

                    private final String  title = "Sample";

                    public SampleView() {
                        setPadding(true);
                        _initLayout();
                    }

                    /** Old Javadoc. */
                    private void _initLayout() {
                        Button button1 = new Button("Old");
                        add(button1);
                    }

                    private void   other() { }
                }
                """;
        DesignNode root = new DesignNode(VerticalLayout.class, null, new DesignNode(Button.class, "New"));

        assertEquals(source.replace("""
                    /** Old Javadoc. */
                    private void _initLayout() {
                        Button button1 = new Button("Old");
                        add(button1);
                    }
                """, indent(JAVADOC + """
                private void _initLayout() {
                    Button button1 = new Button("New");
                    add(button1);
                }
                """)), codec.write(source, root));
    }

    @Test
    void write_withoutMethod_addsMethodCallAndImports() {
        String source = """
                package com.example.views;

                import com.vaadin.flow.component.orderedlayout.VerticalLayout;

                public class SampleView extends VerticalLayout {

                    public SampleView() {
                        setPadding(true);
                    }

                    public SampleView(String title) {
                        this();
                    }
                }
                """;
        DesignNode root = new DesignNode(VerticalLayout.class, null, new DesignNode(TextField.class, "Name"));

        assertEquals("""
                package com.example.views;

                import com.vaadin.flow.component.orderedlayout.VerticalLayout;
                import com.vaadin.flow.component.textfield.TextField;

                public class SampleView extends VerticalLayout {

                    public SampleView() {
                        setPadding(true);
                        _initLayout();
                    }

                    public SampleView(String title) {
                        this();
                    }
                """ + "\n" + indent(JAVADOC + """
                private void _initLayout() {
                    TextField textField1 = new TextField("Name");
                    add(textField1);
                }
                """) + "}\n", codec.write(source, root));
    }

    @Test
    void write_withoutConstructor_addsOneCallingTheMethod() {
        String source = """
                import com.vaadin.flow.component.orderedlayout.VerticalLayout;

                public class SampleView extends VerticalLayout {
                }
                """;

        String written = codec.write(source, new DesignNode(VerticalLayout.class, null));

        assertTrue(written.contains("""
                    public SampleView() {
                        _initLayout();
                    }
                """), written);
        assertEquals(new DesignNode(VerticalLayout.class, null), codec.read(written));
    }

    @Test
    void write_oneLineConstructorAndClass_staysCompilable() {
        String source = """
                import com.vaadin.flow.component.orderedlayout.VerticalLayout;

                public class SampleView extends VerticalLayout {
                    public SampleView() {}
                    public SampleView(int ignored) { setPadding(true); }}
                """;

        assertEquals("""
                import com.vaadin.flow.component.orderedlayout.VerticalLayout;

                public class SampleView extends VerticalLayout {
                    public SampleView() {
                        _initLayout();
                    }
                    public SampleView(int ignored) { setPadding(true);\s
                        _initLayout();
                    }
                """ + "\n" + indent(JAVADOC + """
                private void _initLayout() {
                }
                """) + "}\n", codec.write(source, new DesignNode(VerticalLayout.class, null)));
    }

    @Test
    void write_lineCommentAboveMethod_isKept() {
        String source = viewSource("VerticalLayout", """
                    public SampleView() {
                        _initLayout();
                    }

                    // keep me
                    private void _initLayout() {
                    }
                """);

        String written = codec.write(source, new DesignNode(VerticalLayout.class, null, new DesignNode(Button.class, "Go")));

        assertTrue(written.contains("    // keep me\n    /**\n"), written);
        assertEquals(new DesignNode(VerticalLayout.class, null, new DesignNode(Button.class, "Go")), codec.read(written));
    }

    @Test
    void write_existingMethodNotCalled_addsTheCall() {
        String source = viewSource("VerticalLayout", """
                    public SampleView() {
                    }

                    private void _initLayout() {
                    }
                """);

        String written = codec.write(source, new DesignNode(VerticalLayout.class, null));

        assertTrue(written.contains("""
                    public SampleView() {
                        _initLayout();
                    }
                """), written);
    }

    @Test
    void writeThenRead_everyPaletteType_survives() {
        Set<Class<?>> containers = Set.of(VerticalLayout.class, HorizontalLayout.class, FormLayout.class);
        List<DesignNode> children = Palette.GROUPS.stream()
                .flatMap(group -> group.types().stream())
                .filter(type -> type != Grid.Column.class) // only inside a grid, which the grid entry covers
                .map(type -> containers.contains(type)
                        ? new DesignNode(type, null, new DesignNode(Button.class, "Inside"))
                        : type == Grid.class
                        ? new DesignNode(type, null, new DesignNode(Grid.Column.class, "Header"))
                        : new DesignNode(type, type.getSimpleName() + " text"))
                .toList();
        DesignNode root = new DesignNode(VerticalLayout.class, null, children);

        String written = codec.write(viewSource("VerticalLayout", ""), root);

        assertEquals(root, codec.read(written));
        assertTrue(written.contains("ComboBox<String> comboBox1 = new ComboBox<>(\"ComboBox text\");"), written);
    }

    @Test
    void renderMethod_grid_addsAColumnPerHeader() {
        DesignNode root = new DesignNode(VerticalLayout.class, null, new DesignNode(Grid.class, null,
                new DesignNode(Grid.Column.class, "Name"), new DesignNode(Grid.Column.class, "E-Mail \"work\"")));

        assertEquals(JAVADOC + """
                private void _initLayout() {
                    Grid<String> grid1 = new Grid<>();
                    grid1.addColumn(item -> "").setHeader("Name");
                    grid1.addColumn(item -> "").setHeader("E-Mail \\"work\\"");
                    add(grid1);
                }""", codec.renderMethod(root));
    }

    @Test
    void write_grid_importsGridButNotItsColumnClass() {
        DesignNode root = new DesignNode(VerticalLayout.class, null,
                new DesignNode(Grid.class, null, new DesignNode(Grid.Column.class, "Name")));

        String written = codec.write(viewSource("VerticalLayout", ""), root);

        assertTrue(written.contains("import com.vaadin.flow.component.grid.Grid;\n"), written);
        assertFalse(written.contains("Grid.Column"), written);
        assertEquals(root, codec.read(written));
    }

    @Test
    void read_setHeaderOnSomethingElseThanAGridColumn_fails() {
        String source = viewSource("VerticalLayout", """
                private void _initLayout() {
                    Button button1 = new Button("Save");
                    button1.addColumn(item -> "").setHeader("x");
                    add(button1);
                }
                """);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> codec.read(source));
        assertTrue(exception.getMessage().contains("setHeader"), exception.getMessage());
    }

    @Test
    void read_gridColumnWithRealValueProvider_fails() {
        String source = viewSource("VerticalLayout", """
                private void _initLayout() {
                    Grid<String> grid1 = new Grid<>();
                    grid1.addColumn(item -> item.toUpperCase()).setHeader("Name");
                    add(grid1);
                }
                """).replace("import com.vaadin.flow.router.Route;", "import com.vaadin.flow.router.Route;\nimport com.vaadin.flow.component.grid.Grid;");

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> codec.read(source));
        assertTrue(exception.getMessage().contains("toUpperCase"), exception.getMessage());
    }

    @Test
    void renderMethod_placeholderText_isSetAfterTheDeclaration() {
        DesignNode root = new DesignNode(VerticalLayout.class, null,
                new DesignNode(TextField.class, "Name", "Jane Doe", List.of()));

        assertEquals(JAVADOC + """
                private void _initLayout() {
                    TextField textField1 = new TextField("Name");
                    textField1.setPlaceholder("Jane Doe");
                    add(textField1);
                }""", codec.renderMethod(root));
    }

    @Test
    void writeThenRead_textAndPlaceholderText_survive() {
        DesignNode root = new DesignNode(VerticalLayout.class, null,
                new DesignNode(TextField.class, "Name", "Jane \"JD\" Doe", List.of()),
                new DesignNode(TextField.class, null, "Only a placeholder", List.of()));

        assertEquals(root, codec.read(codec.write(viewSource("VerticalLayout", ""), root)));
    }

    @Test
    void read_setPlaceholderOnUndeclaredVariable_fails() {
        String source = viewSource("VerticalLayout", """
                private void _initLayout() {
                    TextField textField1 = new TextField("Name");
                    other.setPlaceholder("x");
                    add(textField1);
                }
                """);

        IllegalArgumentException exception = assertThrows(IllegalArgumentException.class, () -> codec.read(source));
        assertTrue(exception.getMessage().contains("other.setPlaceholder"), exception.getMessage());
    }

    @Test
    void write_thenRead_givesTheSameTree() {
        DesignNode root = new DesignNode(HorizontalLayout.class, null,
                new DesignNode(VerticalLayout.class, null, new DesignNode(TextField.class, "Name")),
                new DesignNode(Button.class, "Save"));
        String source = """
                package com.example.views;

                import com.vaadin.flow.component.orderedlayout.HorizontalLayout;
                import com.vaadin.flow.router.Route;

                @Route("sample")
                public class SampleView extends HorizontalLayout {

                    public SampleView() {
                    }
                }
                """;

        String written = codec.write(source, root);

        assertEquals(root, codec.read(written));
        assertEquals(written, codec.write(written, root));
    }

    private static String viewSource(String superType, String members) {
        return """
                import com.vaadin.flow.component.button.Button;
                import com.vaadin.flow.component.orderedlayout.HorizontalLayout;
                import com.vaadin.flow.component.orderedlayout.VerticalLayout;
                import com.vaadin.flow.component.textfield.TextField;
                import com.vaadin.flow.router.Route;

                public class SampleView extends %s {
                %s
                }
                """.formatted(superType, members);
    }

    private static String indent(String text) {
        return text.lines().map(line -> line.isEmpty() ? line : "    " + line).collect(Collectors.joining("\n", "", "\n"));
    }

}
