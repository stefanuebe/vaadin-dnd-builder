/**
 * Translates between a design and the designer-owned method of a view's Java source.
 */
public class ViewSourceCodec {

    public static final String METHOD_NAME = "_initLayout";

    private static final String DEFAULT_INDENT = "    ";

    private static final String SET_PLACEHOLDER = "setPlaceholder";

    private static final String ADD_COLUMN = "addColumn";

    private static final String SET_HEADER = "setHeader";

    private static final String METHOD_JAVADOC = """
            Generated by the DnD builder. Do not edit: every save from the builder overwrites this method.
            Once the view is no longer designed with the builder, this method may be edited and renamed freely.""";

    private final JavaParser parser = new JavaParser(new ParserConfiguration().setLanguageLevel(LanguageLevel.JAVA_21));

    private final DefaultPrettyPrinter printer = new DefaultPrettyPrinter(new DefaultPrinterConfiguration()
            .addOption(new DefaultConfigurationOption(ConfigOption.END_OF_LINE_CHARACTER, "\n")));

    /**
     * Renders the designer-owned method that builds the children of the given root, formatted by JavaParser.
     */
    public String renderMethod(DesignNode root) {
        BlockStmt body = new BlockStmt();
        addChildren(body, null, root, new HashMap<>());

        MethodDeclaration method = new MethodDeclaration(new NodeList<>(Modifier.privateModifier()), new VoidType(), METHOD_NAME)
                .setBody(body)
                .setJavadocComment(METHOD_JAVADOC);

        return printer.print(method);
    }

    /**
     * Returns the component type a {@code @Route} view extends, or empty when the source is no such view or its
     * super type cannot be resolved to a component.
     */
    public Optional<Class<? extends Component>> findRouteViewType(String source) {
        CompilationUnit unit = parse(source);
        ClassOrInterfaceDeclaration view = viewClass(unit);
        if (!view.isAnnotationPresent(Route.class) || view.getExtendedTypes().isEmpty()) {
            return Optional.empty();
        }

        try {
            return Optional.of(resolveType(unit, view.getExtendedTypes(0).getNameAsString()));
        } catch (IllegalArgumentException e) {
            return Optional.empty();
        }
    }

    /**
     * Reads the design built by the designer-owned method of the given view source. The root node has the view's
     * super type; a view without the method gives a root without children.
     *
     * @throws IllegalArgumentException when the method contains a statement the designer does not generate, or a
     *                                  type cannot be resolved from the imports
     */
    public DesignNode read(String source) {
        CompilationUnit unit = parse(source);
        ClassOrInterfaceDeclaration view = viewClass(unit);
        if (view.getExtendedTypes().isEmpty()) {
            throw new IllegalArgumentException(view.getNameAsString() + " extends no component");
        }

        PendingNode root = new PendingNode(resolveType(unit, view.getExtendedTypes(0).getNameAsString()), null);
        Map<String, PendingNode> declared = new LinkedHashMap<>();

        List<Statement> statements = view.getMethodsByName(METHOD_NAME).stream()
                .findFirst()
                .flatMap(MethodDeclaration::getBody)
                .map(BlockStmt::getStatements)
                .orElse(new NodeList<>());

        Set<String> added = new HashSet<>();
        for (Statement statement : statements) {
            readStatement(unit, statement, root, declared, added);
        }

        // a component that is never added would silently vanish on the next save
        declared.keySet().stream()
                .filter(variable -> !added.contains(variable))
                .findFirst()
                .ifPresent(variable -> {
                    throw new IllegalArgumentException(variable + " is declared in " + METHOD_NAME + " but never added");
                });

        return root.toDesignNode(declared);
    }

    /**
     * Returns the given view source with the designer-owned method replaced by the given design. A missing method is
     * added at the end of the class and called at the end of the constructors; imports for the design's component
     * types are added. Everything else in the source stays exactly as it is.
     */
    public String write(String source, DesignNode root) {
        CompilationUnit unit = parse(source);
        ClassOrInterfaceDeclaration view = viewClass(unit);
        String memberIndent = view.getMembers().isEmpty() ? DEFAULT_INDENT : indentOf(view.getMembers().get(0));
        Optional<MethodDeclaration> existingMethod = view.getMethodsByName(METHOD_NAME).stream().findFirst();
        List<TextEdit> edits = new ArrayList<>();

        // one edit for all new members, so their order does not depend on how edits at one offset are applied
        String newMembers = constructorIfMissing(view, memberIndent);
        if (existingMethod.isPresent()) {
            edits.add(replaceMethod(source, existingMethod.get(), root));
        } else {
            newMembers += "\n" + indent(renderMethod(root), memberIndent) + "\n";
        }

        if (!newMembers.isEmpty()) {
            edits.add(insertBeforeClosingBrace(source, view.getEnd().orElseThrow(), indentOf(view), newMembers));
        }

        if (!isCalledFromConstructor(view)) {
            edits.addAll(callMethodFromConstructors(source, view, memberIndent));
        }

        edits.addAll(addImports(source, unit, root));

        return applyEdits(source, edits);
    }

    private TextEdit replaceMethod(String source, MethodDeclaration method, DesignNode root) {
        Position start = startOf(method);
        String indent = indentOf(method);
        int end = offset(source, method.getEnd().orElseThrow()) + 1; // the end position is the closing brace itself

        // the first line keeps the indentation that already stands in front of the method
        return new TextEdit(offset(source, start), end, indent(renderMethod(root), indent).substring(indent.length()));
    }

    private String constructorIfMissing(ClassOrInterfaceDeclaration view, String memberIndent) {
        if (!view.getConstructors().isEmpty()) {
            return "";
        }

        return "\n" + memberIndent + "public " + view.getNameAsString() + "() {\n"
                + memberIndent + DEFAULT_INDENT + METHOD_NAME + "();\n"
                + memberIndent + "}\n";
    }

    /**
     * Adds a call of the designer-owned method at the end of each constructor that does not delegate to another one.
     */
    private List<TextEdit> callMethodFromConstructors(String source, ClassOrInterfaceDeclaration view, String memberIndent) {
        String call = memberIndent + DEFAULT_INDENT + METHOD_NAME + "();\n";

        return view.getConstructors().stream()
                .filter(constructor -> !delegatesToThis(constructor))
                .map(constructor -> insertBeforeClosingBrace(source, constructor.getBody().getEnd().orElseThrow(),
                        memberIndent, call))
                .toList();
    }

    private boolean delegatesToThis(ConstructorDeclaration constructor) {
        return constructor.getBody().getStatements().stream()
                .anyMatch(statement -> statement.isExplicitConstructorInvocationStmt()
                        && statement.asExplicitConstructorInvocationStmt().isThis());
    }

    private boolean isCalledFromConstructor(ClassOrInterfaceDeclaration view) {
        return view.getConstructors().stream()
                .flatMap(constructor -> constructor.findAll(MethodCallExpr.class).stream())
                .anyMatch(call -> call.getScope().isEmpty() && call.getNameAsString().equals(METHOD_NAME));
    }

    /**
     * Inserts lines in front of a closing brace. A brace alone on its line keeps its line; a brace behind other code
     * (like {@code public View() {}}) moves to a new line with the given indentation.
     */
    private TextEdit insertBeforeClosingBrace(String source, Position closingBrace, String braceIndent, String lines) {
        int brace = offset(source, closingBrace);
        int lineStart = lineStart(source, closingBrace);
        if (source.substring(lineStart, brace).isBlank()) {
            return new TextEdit(lineStart, lineStart, lines);
        }

        return new TextEdit(brace, brace, "\n" + lines + braceIndent);
    }

    /**
     * Adds an import for each component type of the design that the source does not import yet, after the last
     * import (or the package declaration).
     */
    private List<TextEdit> addImports(String source, CompilationUnit unit, DesignNode root) {
        String missingImports = componentTypes(root)
                .filter(type -> !type.isMemberClass()) // grid columns come with their grid
                .filter(type -> !isImported(unit, type))
                .map(type -> "import " + type.getCanonicalName() + ";\n")
                .distinct()
                .sorted()
                .collect(Collectors.joining());
        if (missingImports.isEmpty()) {
            return List.of();
        }

        Optional<Position> anchor = unit.getImports().isEmpty()
                ? unit.getPackageDeclaration().flatMap(Node::getEnd)
                : unit.getImports().get(unit.getImports().size() - 1).getEnd();
        if (anchor.isEmpty()) {
            return List.of(new TextEdit(0, 0, missingImports + "\n"));
        }

        int afterAnchor = source.indexOf('\n', offset(source, anchor.get())) + 1;
        String separator = unit.getImports().isEmpty() ? "\n" : "";

        return List.of(new TextEdit(afterAnchor, afterAnchor, separator + missingImports));
    }

    private Stream<Class<? extends Component>> componentTypes(DesignNode node) {
        return Stream.concat(Stream.of(node.type()), node.children().stream().flatMap(this::componentTypes));
    }

    private boolean isImported(CompilationUnit unit, Class<? extends Component> type) {
        return unit.getImports().stream()
                .filter(importDeclaration -> !importDeclaration.isStatic())
                .anyMatch(importDeclaration -> importDeclaration.isAsterisk()
                        ? importDeclaration.getNameAsString().equals(type.getPackageName())
                        : importDeclaration.getNameAsString().equals(type.getCanonicalName()));
    }

    /**
     * Where a node starts in the source, including its Javadoc; other comments in front of it are not part of it.
     */
    private Position startOf(Node node) {
        return node.getComment()
                .filter(Comment::isJavadocComment)
                .flatMap(Node::getBegin)
                .orElseGet(() -> node.getBegin().orElseThrow());
    }

    private String indentOf(Node node) {
        return " ".repeat(startOf(node).column - 1);
    }

    private String indent(String text, String indent) {
        return text.lines()
                .map(line -> line.isEmpty() ? line : indent + line)
                .collect(Collectors.joining("\n"));
    }

    private int offset(String source, Position position) {
        int lineStart = 0;
        for (int line = 1; line < position.line; line++) {
            lineStart = source.indexOf('\n', lineStart) + 1;
        }

        return lineStart + position.column - 1;
    }

    private int lineStart(String source, Position position) {
        return offset(source, new Position(position.line, 1));
    }

    /**
     * Applies the edits back to front, so earlier offsets stay valid.
     */
    private String applyEdits(String source, List<TextEdit> edits) {
        StringBuilder result = new StringBuilder(source);
        edits.stream()
                .sorted(Comparator.comparingInt(TextEdit::start).reversed())
                .forEach(edit -> result.replace(edit.start(), edit.end(), edit.text()));

        return result.toString();
    }

    private void readStatement(CompilationUnit unit, Statement statement, PendingNode root,
                               Map<String, PendingNode> declared, Set<String> added) {
        Expression expression = statement.toExpressionStmt()
                .map(ExpressionStmt::getExpression)
                .orElseThrow(() -> unsupported(statement));

        if (expression instanceof VariableDeclarationExpr declaration && declaration.getVariables().size() == 1) {
            VariableDeclarator variable = declaration.getVariable(0);
            ObjectCreationExpr creation = variable.getInitializer()
                    .filter(Expression::isObjectCreationExpr)
                    .map(Expression::asObjectCreationExpr)
                    .orElseThrow(() -> unsupported(statement));
            Class<? extends Component> type = resolveType(unit, creation.getType().getNameAsString());

            declared.put(variable.getNameAsString(), new PendingNode(type, readText(creation, statement)));
            return;
        }

        if (expression instanceof MethodCallExpr call && call.getNameAsString().equals(SET_PLACEHOLDER)) {
            PendingNode node = call.getScope()
                    .filter(Expression::isNameExpr)
                    .map(scope -> declared.get(scope.asNameExpr().getNameAsString()))
                    .orElse(null);
            if (node == null || call.getArguments().size() != 1 || !call.getArgument(0).isStringLiteralExpr()) {
                throw unsupported(statement);
            }

            node.placeholder = call.getArgument(0).asStringLiteralExpr().asString();
            return;
        }

        if (expression instanceof MethodCallExpr call && call.getNameAsString().equals(SET_HEADER)) {
            readColumn(call, declared).orElseThrow(() -> unsupported(statement));
            return;
        }

        if (expression instanceof MethodCallExpr call && call.getNameAsString().equals("add")) {
            PendingNode parent = findAddTarget(call, root, declared);
            if (parent == null) {
                throw unsupported(statement);
            }

            for (Expression argument : call.getArguments()) {
                boolean addsDeclaredVariableOnce = argument.isNameExpr()
                        && declared.containsKey(argument.asNameExpr().getNameAsString())
                        && added.add(argument.asNameExpr().getNameAsString());
                if (!addsDeclaredVariableOnce) {
                    throw unsupported(statement);
                }

                parent.childVariables.add(argument.asNameExpr().getNameAsString());
            }
            return;
        }

        throw unsupported(statement);
    }

    /**
     * Reads {@code grid.addColumn(item -> "").setHeader("Header")} into a column of a declared grid; empty when the
     * call has any other shape.
     */
    private Optional<PendingNode> readColumn(MethodCallExpr setHeader, Map<String, PendingNode> declared) {
        if (setHeader.getArguments().size() != 1 || !setHeader.getArgument(0).isStringLiteralExpr()
                || setHeader.getScope().isEmpty() || !setHeader.getScope().get().isMethodCallExpr()) {
            return Optional.empty();
        }

        MethodCallExpr addColumn = setHeader.getScope().get().asMethodCallExpr();
        if (!addColumn.getNameAsString().equals(ADD_COLUMN) || addColumn.getArguments().size() != 1
                || !isGeneratedValueProvider(addColumn.getArgument(0))
                || addColumn.getScope().isEmpty() || !addColumn.getScope().get().isNameExpr()) {
            return Optional.empty();
        }

        PendingNode grid = declared.get(addColumn.getScope().get().asNameExpr().getNameAsString());
        if (grid == null || grid.type != Grid.class) {
            return Optional.empty();
        }

        grid.columnHeaders.add(setHeader.getArgument(0).asStringLiteralExpr().asString());
        return Optional.of(grid);
    }

    /**
     * Whether the column's value provider is the generated stand-in {@code item -> ""}; any other one would be lost on
     * the next save.
     */
    private boolean isGeneratedValueProvider(Expression valueProvider) {
        return valueProvider.isLambdaExpr() && valueProvider.asLambdaExpr().getExpressionBody()
                .filter(body -> body.isStringLiteralExpr() && body.asStringLiteralExpr().getValue().isEmpty())
                .isPresent();
    }

    /**
     * Returns the node an {@code add(...)} call adds to: the root when unscoped, a declared variable otherwise, or
     * {@code null} when the scope is anything else.
     */
    private PendingNode findAddTarget(MethodCallExpr call, PendingNode root, Map<String, PendingNode> declared) {
        Optional<Expression> scope = call.getScope();
        if (scope.isEmpty()) {
            return root;
        }

        return scope.get().isNameExpr() ? declared.get(scope.get().asNameExpr().getNameAsString()) : null;
    }

    private String readText(ObjectCreationExpr creation, Statement statement) {
        NodeList<Expression> arguments = creation.getArguments();
        if (arguments.isEmpty()) {
            return null;
        }

        if (arguments.size() > 1 || !arguments.get(0).isStringLiteralExpr()) {
            throw unsupported(statement);
        }

        return arguments.get(0).asStringLiteralExpr().asString();
    }

    private CompilationUnit parse(String source) {
        ParseResult<CompilationUnit> result = parser.parse(source);

        return result.getResult()
                .filter(unit -> result.isSuccessful())
                .orElseThrow(() -> new IllegalArgumentException("Cannot parse the view source: " + result.getProblems()));
    }

    private IllegalArgumentException unsupported(Statement statement) {
        return new IllegalArgumentException("Unsupported statement in " + METHOD_NAME + ": " + statement);
    }

    /**
     * Returns the {@code @Route} class of the source, or its first class when none has the annotation.
     */
    private ClassOrInterfaceDeclaration viewClass(CompilationUnit unit) {
        List<ClassOrInterfaceDeclaration> classes = unit.getTypes().stream()
                .filter(ClassOrInterfaceDeclaration.class::isInstance)
                .map(ClassOrInterfaceDeclaration.class::cast)
                .toList();
        if (classes.isEmpty()) {
            throw new IllegalArgumentException("The source declares no class");
        }

        return classes.stream()
                .filter(type -> type.isAnnotationPresent(Route.class))
                .findFirst()
                .orElse(classes.get(0));
    }

    /**
     * Resolves a simple type name through the single-type and on-demand imports of the source.
     */
    private Class<? extends Component> resolveType(CompilationUnit unit, String simpleName) {
        for (ImportDeclaration importDeclaration : unit.getImports()) {
            if (importDeclaration.isStatic()) {
                continue;
            }

            String importedName = importDeclaration.getNameAsString();
            if (importDeclaration.isAsterisk()) {
                importedName += "." + simpleName;
            } else if (!importDeclaration.getName().getIdentifier().equals(simpleName)) {
                continue;
            }

            try {
                Class<?> type = Class.forName(importedName, false, getClass().getClassLoader());
                if (Component.class.isAssignableFrom(type)) {
                    return type.asSubclass(Component.class);
                }
            } catch (ClassNotFoundException e) {
                // an on-demand import that does not contain the type; try the next import
            }
        }

        throw new IllegalArgumentException("Cannot resolve component type " + simpleName + " from the imports");
    }

    /**
     * Declares a variable per child (depth-first), then adds all children to the parent in one call. A
     * {@code null} parent variable means the view itself.
     */
    private void addChildren(BlockStmt body, String parentVariable, DesignNode parent, Map<String, Integer> counters) {
        if (parent.children().isEmpty()) {
            return;
        }

        if (parent.type() == Grid.class) {
            // a column per child; the empty value is a stand-in until the grid gets real items
            for (DesignNode column : parent.children()) {
                MethodCallExpr addColumn = new MethodCallExpr(new NameExpr(parentVariable), ADD_COLUMN,
                        new NodeList<>(new LambdaExpr(new Parameter(new UnknownType(), "item"), new StringLiteralExpr(""))));
                body.addStatement(new MethodCallExpr(addColumn, SET_HEADER,
                        new NodeList<>(new StringLiteralExpr().setString(column.text()))));
            }
            return;
        }

        NodeList<Expression> childVariables = new NodeList<>();
        for (DesignNode child : parent.children()) {
            String variable = declare(body, child, counters);
            addChildren(body, variable, child, counters);
            childVariables.add(new NameExpr(variable));
        }

        NameExpr scope = parentVariable == null ? null : new NameExpr(parentVariable);
        body.addStatement(new MethodCallExpr(scope, "add", childVariables));
    }

    private String declare(BlockStmt body, DesignNode node, Map<String, Integer> counters) {
        String typeName = node.type().getSimpleName();
        String variable = StringUtils.uncapitalize(typeName) + counters.merge(typeName, 1, Integer::sum);

        NodeList<Expression> arguments = new NodeList<>();
        if (node.text() != null) {
            // setString escapes quotes, backslashes and line breaks; the String constructor would not
            arguments.add(new StringLiteralExpr().setString(node.text()));
        }

        ClassOrInterfaceType type = new ClassOrInterfaceType(null, typeName);
        ClassOrInterfaceType createdType = type.clone();
        if (node.type().getTypeParameters().length > 0) {
            // generic components like ComboBox get String items: ComboBox<String> comboBox1 = new ComboBox<>(...)
            type.setTypeArguments(new ClassOrInterfaceType(null, "String"));
            createdType.setTypeArguments(new NodeList<>());
        }

        body.addStatement(new VariableDeclarationExpr(
                new VariableDeclarator(type, variable, new ObjectCreationExpr(null, createdType, arguments))));

        if (node.placeholder() != null) {
            body.addStatement(new MethodCallExpr(new NameExpr(variable), SET_PLACEHOLDER,
                    new NodeList<>(new StringLiteralExpr().setString(node.placeholder()))));
        }

        return variable;
    }

    /**
     * Replaces the source between {@code start} (inclusive) and {@code end} (exclusive) with {@code text}.
     */
    private record TextEdit(int start, int end, String text) {
    }

    /**
     * A node while reading, before all {@code add(...)} calls are known; children are referenced by variable name.
     */
    private static final class PendingNode {

        private final Class<? extends Component> type;
        private final String text;
        private final List<String> childVariables = new ArrayList<>();
        private final List<String> columnHeaders = new ArrayList<>();
        private String placeholder;

        PendingNode(Class<? extends Component> type, String text) {
            this.type = type;
            this.text = text;
        }

        DesignNode toDesignNode(Map<String, PendingNode> declared) {
            Stream<DesignNode> columns = columnHeaders.stream().map(header -> new DesignNode(Grid.Column.class, header));
            Stream<DesignNode> children = childVariables.stream()
                    .map(variable -> declared.get(variable).toDesignNode(declared));

            return new DesignNode(type, text, placeholder, Stream.concat(columns, children).toList());
        }
    }

}
