package com.example.application.views;

import com.vaadin.flow.component.button.Button;
import com.vaadin.flow.component.checkbox.Checkbox;
import com.vaadin.flow.component.combobox.ComboBox;
import com.vaadin.flow.component.formlayout.FormLayout;
import com.vaadin.flow.component.html.H2;
import com.vaadin.flow.component.orderedlayout.HorizontalLayout;
import com.vaadin.flow.component.orderedlayout.VerticalLayout;
import com.vaadin.flow.component.textfield.EmailField;
import com.vaadin.flow.component.textfield.TextArea;
import com.vaadin.flow.component.textfield.TextField;
import com.vaadin.flow.router.Route;

/**
 * A sample form to design in the DnD builder: a form layout with fields, a checkbox and buttons.
 */
@Route("contact")
public class ContactFormView extends VerticalLayout {

    public ContactFormView() {
        _initLayout();
    }

    /**
     * Generated by the DnD builder. Do not edit: every save from the builder overwrites this method.
     * Once the view is no longer designed with the builder, this method may be edited and renamed freely.
     */
    private void _initLayout() {
        H2 h21 = new H2("Contact us");
        FormLayout formLayout1 = new FormLayout();
        TextField textField1 = new TextField("First name");
        textField1.setPlaceholder("Jane");
        TextField textField2 = new TextField("Last name");
        textField2.setPlaceholder("Doe");
        EmailField emailField1 = new EmailField("Email");
        emailField1.setPlaceholder("jane.doe@example.com");
        ComboBox<String> comboBox1 = new ComboBox<>("Topic");
        TextArea textArea1 = new TextArea("Message");
        formLayout1.add(textField1, textField2, emailField1, comboBox1, textArea1);
        Checkbox checkbox1 = new Checkbox("Send me a copy");
        HorizontalLayout horizontalLayout1 = new HorizontalLayout();
        Button button1 = new Button("Send");
        Button button2 = new Button("Cancel");
        horizontalLayout1.add(button1, button2);
        add(h21, formLayout1, checkbox1, horizontalLayout1);
    }
}
