package com.example.application.views;

import com.vaadin.flow.component.button.Button;
import com.vaadin.flow.component.datepicker.DatePicker;
import com.vaadin.flow.component.grid.Grid;
import com.vaadin.flow.component.html.H2;
import com.vaadin.flow.component.html.Paragraph;
import com.vaadin.flow.component.orderedlayout.HorizontalLayout;
import com.vaadin.flow.component.orderedlayout.VerticalLayout;
import com.vaadin.flow.component.textfield.TextField;
import com.vaadin.flow.router.Route;

/**
 * A sample list to design in the DnD builder: a search bar, a grid with columns and actions.
 */
@Route("customers")
public class CustomerListView extends VerticalLayout {

    public CustomerListView() {
        _initLayout();
    }

    /**
     * Generated by the DnD builder. Do not edit: every save from the builder overwrites this method.
     * Once the view is no longer designed with the builder, this method may be edited and renamed freely.
     */
    private void _initLayout() {
        H2 h21 = new H2("Customers");
        Paragraph paragraph1 = new Paragraph("All customers with an active contract.");
        HorizontalLayout horizontalLayout1 = new HorizontalLayout();
        TextField textField1 = new TextField("Search");
        textField1.setPlaceholder("Name or email");
        DatePicker datePicker1 = new DatePicker("Customer since");
        Button button1 = new Button("Search");
        horizontalLayout1.add(textField1, datePicker1, button1);
        Grid<String> grid1 = new Grid<>();
        grid1.addColumn(item -> "").setHeader("Name");
        grid1.addColumn(item -> "").setHeader("Email");
        grid1.addColumn(item -> "").setHeader("City");
        grid1.addColumn(item -> "").setHeader("Customer since");
        HorizontalLayout horizontalLayout2 = new HorizontalLayout();
        Button button2 = new Button("New customer");
        Button button3 = new Button("Export");
        horizontalLayout2.add(button2, button3);
        add(h21, paragraph1, horizontalLayout1, grid1, horizontalLayout2);
    }
}
